package dev.amps.app.data.remote

/**
 * Поиск по описанию внешности: не скрейпер, а готовые ссылки.
 *
 * ## Почему здесь нет разбора HTML
 *
 * Проверено с рабочей машины: и DuckDuckGo, и Mojeek на автоматический
 * запрос отдают страницу с капчей — DuckDuckGo присылает `anomaly-modal__puzzle`,
 * Mojeek — `captcha-wrap`, причём с кодом 200. То есть запрос выглядит
 * успешным, а внутри — антибот.
 *
 * Собирать на этом выдачу значит вшить в приложение конструкцию, которая
 * рано или поздно сломается: то ли капча придёт на телефоне по мобильному
 * адресу, то ли поисковик поменяет вёрстку. Приложение, которое молча
 * перестаёт искать, хуже приложения, которое честно отправляет по ссылке.
 *
 * Поэтому здесь ровно то, что не ломается: запрос собирается и
 * превращается в готовые адреса. Нажатие открывает обычный поиск в браузере,
 * где человек и капчу пройдёт, если она появится.
 *
 * ## Почему вообще это нужно
 *
 * Ни IQDB, ни тегер не находят скриншот из серии: первый индексирует
 * бо́ру-арты, второй обучен на том же. Остаётся путь через то, что тегер
 * определяет безошибочно, — цвет волос, глаза, одежду.
 */
class AppearanceSearchClient {

    /** Готовая ссылка на поиск. */
    data class SearchLink(
        val engine: String,
        val url: String,
    )

    /**
     * Собирает запрос из признаков внешности.
     *
     * Порядок важен: то, что встречается реже, ставится первым. «Длинные
     * белые волосы, красные глаза, чокер» встречается в десятки раз реже,
     * чем просто «зелёные глаза», а поисковики весят слова слева направо.
     */
    fun buildQuery(clauses: List<Pair<String, List<String>>>): String? {
        val distinctive = clauses
            .filter { (group, _) -> group in PRIORITY_GROUPS }
            .flatMap { (_, phrases) -> phrases }
            .take(MAX_PHRASES)

        if (distinctive.isEmpty()) return null

        // Слова «аниме персонаж» обязательны: без них запрос «длинные волосы»
        // уводит в каталоги причёсок, а не в поиск персонажа.
        return (distinctive.joinToString(" ") + " " + SUBJECT_HINT).trim()
    }

    /**
     * Разворачивает запрос в ссылки на несколько поисковиков.
     *
     * Несколько — потому что бесплатный поисковик рано или поздно заблокирует
     * адрес, и кнопка без запасного варианта окажется мёртвой.
     */
    fun links(query: String): List<SearchLink> {
        val encoded = java.net.URLEncoder.encode(query, "UTF-8")
        return listOf(
            SearchLink("DuckDuckGo", "https://duckduckgo.com/?q=$encoded"),
            SearchLink("Яндекс", "https://yandex.ru/search/?text=$encoded"),
            SearchLink("Google", "https://www.google.com/search?q=$encoded"),
        )
    }

    private companion object {
        const val SUBJECT_HINT = "аниме персонаж"
        const val MAX_PHRASES = 6

        /** Группы, которые различают персонажа лучше всего. */
        val PRIORITY_GROUPS = setOf("Одежда", "Аксессуары", "Глаза", "Волосы")
    }
}