package dev.amps.app.data.model

import kotlinx.serialization.Serializable

/**
 * Готовая ссылка на поиск по описанию внешности.
 *
 * Именно ссылка, а не выдача поисковика: и DuckDuckGo, и Mojeek на
 * автоматический запрос отдают страницу с капчей (проверено — при коде 200
 * внутри оказывается `anomaly-modal__puzzle` и `captcha-wrap` соответственно).
 * Разбирать такую выдачу значит вшить в приложение то, что рано или поздно
 * сломается. Ссылка не ломается: её открывает обычный браузер, где капчу при
 * необходимости проходит человек.
 */
@Serializable
data class SearchLink(
    /** Название поисковика для кнопки. */
    val engine: String,
    val url: String,
)